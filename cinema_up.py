def rec(name, status, detail=""):
    RESULTS.append((name, status, detail))
    print("[%s] %s%s" % (status, name, (": " + detail) if detail else ""), flush=True)

def fetch(cfg, path, timeout=8):
    url = "http://%s:%d%s" % (cfg.host, cfg.port, path)
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.status, r.read(300000).decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        return e.code, ""
    except Exception as e:
        return 0, str(e)

def preflight(cfg):
    rec("python", "PASS", sys.version.split()[0])
    for mod in ("flask", "edge_tts"):
        ok = importlib.util.find_spec(mod) is not None
        rec(mod, "PASS" if ok else "FAIL", "" if ok else "missing here: run with .venv/bin/python")
    for tool in ("ffmpeg", "ffprobe"):
        rec(tool, "PASS" if shutil.which(tool) else "FAIL")
    free = shutil.disk_usage(ROOT).free // 1048576
    rec("disk", "PASS" if free >= cfg.min_free_mb else "FAIL", "%d MB free (min %d)" % (free, cfg.min_free_mb))

def build_kaggle():
    src = ROOT / "gpu_worker" / "cinema_worker.py"
    out = ROOT / "gpu_worker" / "kaggle_all_in_one.py"
    if not src.exists():
        return rec("kaggle file", "FAIL", "gpu_worker/cinema_worker.py is missing")
    text, marker = src.read_text(encoding="utf-8"), 'if __name__ == "__main__":'
    if text.count(marker) != 1:
        return rec("kaggle file", "FAIL", "unexpected worker layout, not generated")
    if out.exists() and not out.read_text(encoding="utf-8").startswith(HEADER):
        return rec("kaggle file", "FAIL", "%s exists and is not generated by this script; not overwritten" % out.name)
    body = HEADER + text.split(marker)[0] + LAUNCH
    try:
        compile(body, str(out), "exec")
    except SyntaxError as e:
        return rec("kaggle file", "FAIL", "does not compile: %s" % e)
    out.write_text(body, encoding="utf-8")
    rec("kaggle file", "PASS", "%s (%d lines, compiles)" % (out.relative_to(ROOT), body.count("\n")))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-backup", action="store_true")
    ap.add_argument("--tests", action="store_true", help="also run the whole test suite (slow)")
    args = ap.parse_args()
    from cinema_core import backup, config, lifecycle
    cfg = config.load()
    print("== CINEMA UP ==", flush=True)
    preflight(cfg)
    if not args.no_backup:
        try:
            path, n = backup.create(cfg)
            rec("backup", "PASS", "%s (%d files, verified)" % (path.name, n))
        except Exception as e:
            rec("backup", "FAIL", str(e))
            print("Stopping: no safe backup, nothing was changed.")
            return 1
    build_kaggle()
    lifecycle.stop(cfg)
    code, msg = lifecycle.start(cfg)
    rec("server", "PASS" if code == 0 else "FAIL", msg.splitlines()[0] if code == 0 else msg[-600:])
    if code == 0:
        for path, want in [("/health", 200), ("/", 200), ("/produce", 200), ("/api/projects", 200),
                           ("/api/providers", 200), ("/api/vidgen/status", 200), ("/api/prod/capabilities", 200)]:
            got, _ = fetch(cfg, path)
            rec("GET " + path, "PASS" if got == want else "FAIL", "" if got == want else "HTTP %s" % got)
        got, body = fetch(cfg, "/api/vidgen/status")
        try:
            vs = json.loads(body) if got == 200 else {}
        except ValueError:
            vs = {}
        if vs.get("ready"):
            rec("gpu worker", "PASS", "model %s" % vs.get("model"))
            print("-- real generation test (can take minutes) --", flush=True)
            r = subprocess.run([sys.executable, "-m", "studio.vidgen", "test"], timeout=2400)
            rec("real video generation", "PASS" if r.returncode == 0 else "FAIL",
                "see var/vidgen/test.mp4: a valid file is NOT proof of quality, watch it" if r.returncode == 0 else "see the output above")
        else:
            rec("gpu worker", "BLOCKED", "BLOCKED — GPU WORKER NOT AVAILABLE (%s)" % (vs.get("reason") or "unknown"))
    if args.tests:
        print("-- full test suite --", flush=True)
        r = subprocess.run([sys.executable, "-m", "pytest", "-q", "tests"], capture_output=True, text=True, timeout=1500)
        last = [l for l in r.stdout.strip().splitlines() if l.strip()][-1:] or [""]
        rec("test suite", "PASS" if r.returncode == 0 else "FAIL", last[0])
    print("\n== REPORT ==")
    for name, st, d in RESULTS:
        print("%-8s %s" % (st, name))
    if any(st == "BLOCKED" for _, st, _ in RESULTS):
        print("""
NEXT (free GPU path, needs a phone-verified Kaggle account):
 1. Make a private token and keep it secret:  python -c "import secrets;print(secrets.token_hex(24))"
 2. Kaggle notebook: Settings > Accelerator = GPU T4, Internet = ON; Add-ons > Secrets: CINEMA_WORKER_TOKEN = that token
 3. Paste gpu_worker/kaggle_all_in_one.py into one cell and run it. Wait for "WORKER READY" and its URL.
    (untested: model RAM/VRAM fit and whether the platform allows the tunnel are unknown until you try)
 4. Termux: export CINEMA_WORKER_URL=<url> CINEMA_WORKER_TOKEN=<token>; .venv/bin/python cinema_up.py""")
    return 1 if any(st == "FAIL" for _, st, _ in RESULTS) else 0

if __name__ == "__main__":
    sys.exit(main())
